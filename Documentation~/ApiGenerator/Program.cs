using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

if (args is not [("framework" or "project") and var scope, var rootArgument])
{
    Console.Error.WriteLine("Usage: ApiGenerator <framework|project> <repository-root>");
    return 1;
}

bool framework = scope == "framework";
string root = Path.GetFullPath(rootArgument);
string[] sourceRoots = framework
    ? ["Framework", "Integrations", "Editor", "Samples~"]
    : ["Assets/Scripts", "Assets/Editor", "Assets/Prototypes"];
string output = Path.Combine(root, framework ? "Documentation~/API" : "Documentation/API");
const string generatedMarker = "<!-- Generated by ApiGenerator. -->";

// Cover the conditional declarations used in the package and sandbox without loading Unity assemblies.
string[][] platforms = [["UNITY_EDITOR", "UNITY_STANDALONE"], ["UNITY_STANDALONE"], ["UNITY_WEBGL"], []];
CSharpParseOptions[] configurations =
    (from platform in platforms
     from modernUnity in new[] { true, false }
     from inputSystem in new[] { true, false }
     select new CSharpParseOptions(LanguageVersion.Latest, DocumentationMode.Parse,
         preprocessorSymbols: platform
             .Concat(modernUnity ? ["UNITY_6000_4_OR_NEWER"] : Array.Empty<string>())
             .Concat(inputSystem ? ["ENABLE_INPUT_SYSTEM"] : Array.Empty<string>())))
    .ToArray();

SortedDictionary<string, ApiType> types = new(StringComparer.Ordinal);
int files = 0;
foreach (string sourceRoot in sourceRoots)
{
    foreach (string file in Directory.EnumerateFiles(Path.Combine(root, sourceRoot), "*.cs", SearchOption.AllDirectories)
        .Order(StringComparer.Ordinal))
    {
        string relative = Path.GetRelativePath(root, file).Replace('\\', '/');
        if (relative.Split('/').Contains("Tests", StringComparer.OrdinalIgnoreCase))
            continue;

        files++;
        string source = File.ReadAllText(file);
        CSharpParseOptions[] options = source.Contains("#if", StringComparison.Ordinal)
            ? configurations
            : [configurations[0]];
        foreach (CSharpParseOptions configuration in options)
        {
            SyntaxTree tree = CSharpSyntaxTree.ParseText(source, configuration, file);
            Diagnostic[] errors = tree.GetDiagnostics().Where(error => error.Severity == DiagnosticSeverity.Error).ToArray();
            if (errors.Length > 0)
                throw new InvalidOperationException(string.Join(Environment.NewLine, errors.Select(error => error.ToString())));

            foreach (MemberDeclarationSyntax declaration in tree.GetRoot().DescendantNodes(
                node => node is CompilationUnitSyntax or BaseNamespaceDeclarationSyntax or BaseTypeDeclarationSyntax)
                .OfType<MemberDeclarationSyntax>().Where(node => node is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax))
            {
                bool visibleType = IsVisible(declaration) &&
                    declaration.Ancestors().OfType<BaseTypeDeclarationSyntax>().All(IsVisible);
                bool hasMenu = declaration is TypeDeclarationSyntax menuType && menuType.Members.Any(HasMenuAttribute);
                if (!visibleType && !hasMenu)
                    continue;

                string name = declaration switch
                {
                    BaseTypeDeclarationSyntax type => type.Identifier.ValueText,
                    DelegateDeclarationSyntax callable => callable.Identifier.ValueText,
                    _ => throw new InvalidOperationException(),
                };
                string qualifiedName = QualifiedName(declaration);
                string key = SourceDomain(relative) + ":" + qualifiedName;
                if (!types.TryGetValue(key, out ApiType? api))
                {
                    string anchor = "type-" + Slug(name) + "-" +
                        Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(key)))[..10].ToLowerInvariant();
                    types.Add(key, api = new ApiType(name, qualifiedName, anchor, Group(relative)));
                }

                Add(api.Declarations, declaration, relative);
                IEnumerable<MemberDeclarationSyntax> members = declaration switch
                {
                    TypeDeclarationSyntax type => type.Members.Where(member =>
                        member is not (BaseTypeDeclarationSyntax or DelegateDeclarationSyntax) &&
                        (HasMenuAttribute(member) || (visibleType &&
                            (IsVisible(member) || IsExplicitInterfaceImplementation(member) || HasSerializationAttribute(member))))),
                    EnumDeclarationSyntax enumeration => enumeration.Members,
                    _ => [],
                };
                foreach (MemberDeclarationSyntax member in members)
                    Add(api.Members, member, relative);
            }
        }
    }
}

if (types.Count == 0)
    throw new InvalidOperationException("No API types were found in " + root);

Directory.CreateDirectory(output);
HashSet<string> written = new(StringComparer.OrdinalIgnoreCase);
var groups = types.Values.GroupBy(type => type.Group).OrderBy(group => group.Key, StringComparer.Ordinal).ToArray();
StringBuilder index = new();
index.AppendLine("---").AppendLine("title: API index").AppendLine("sidebar_position: 0")
    .AppendLine("hide_table_of_contents: true").AppendLine("---").AppendLine()
    .AppendLine(framework ? "# Framework API" : "# Sandbox API").AppendLine()
    .AppendLine("Browse a system or use your browser's Find command to jump to a type. The reference is generated from the C# source in this checkout.")
    .AppendLine().AppendLine("Signatures cover declared public and protected APIs, explicit interface implementations, attributed serialization members on visible types, and Unity menu commands. Platform-specific declarations appear alongside the others. Follow the source link to check conditional compilation, initialization, and usage.")
    .AppendLine().AppendLine("## Systems").AppendLine();

foreach (var group in groups)
{
    string page = "system-" + Slug(group.Key) + ".md";
    StringBuilder markdown = new();
    markdown.AppendLine("# " + group.Key).AppendLine()
        .AppendLine("[Browse all API types](./api-index.md)").AppendLine();
    index.AppendLine($"- [{group.Key}](./{page})");

    foreach (ApiType api in group.OrderBy(type => type.QualifiedName, StringComparer.Ordinal))
    {
        markdown.AppendLine($"## `{api.QualifiedName}` {{#{api.Anchor}}}").AppendLine();
        foreach (ApiDeclaration declaration in api.Declarations.Values)
            AppendDeclaration(markdown, declaration);
        foreach (ApiDeclaration member in api.Members.Values)
            AppendDeclaration(markdown, member);
    }

    Write(page, markdown);
}

index.AppendLine().AppendLine("## Types").AppendLine();
foreach (ApiType api in types.Values.OrderBy(type => type.Name, StringComparer.OrdinalIgnoreCase)
    .ThenBy(type => type.QualifiedName, StringComparer.Ordinal))
    index.AppendLine($"- [`{api.QualifiedName}`](./system-{Slug(api.Group)}.md#{api.Anchor}) · {api.Group}");
Write("api-index.md", index);

foreach (string file in Directory.EnumerateFiles(output, "system-*.md"))
{
    if (!written.Contains(Path.GetFileName(file)) && File.ReadLines(file).FirstOrDefault() == generatedMarker)
        File.Delete(file);
}

Console.WriteLine($"{scope}: {types.Count} types, {types.Values.Sum(type => type.Members.Count)} member declarations, " +
    $"{groups.Length} system pages from {files} C# source files.");
return 0;

void Write(string fileName, StringBuilder markdown)
{
    if (!written.Add(fileName))
        throw new InvalidOperationException("Duplicate API filename: " + fileName);
    // The index has front matter. System pages use their top heading as the title.
    string content = fileName == "api-index.md" ? markdown.ToString() : generatedMarker + "\n\n" + markdown;
    File.WriteAllText(Path.Combine(output, fileName), content.ReplaceLineEndings("\n"));
}

static bool HasMenuAttribute(MemberDeclarationSyntax node) => AttributeNames(node)
    .Any(name => name is "MenuItem" or "ContextMenu" or "MenuItemAttribute" or "ContextMenuAttribute");

static bool HasSerializationAttribute(MemberDeclarationSyntax node) => AttributeNames(node)
    .Any(name => name is "SerializeField" or "SerializeReference" or "SerializeFieldAttribute" or "SerializeReferenceAttribute");

static IEnumerable<string> AttributeNames(MemberDeclarationSyntax node) => node.AttributeLists
    .SelectMany(list => list.Attributes).Select(attribute => attribute.Name.ToString().Split('.').Last());

static bool IsVisible(MemberDeclarationSyntax node)
{
    if (node.Modifiers.Any(SyntaxKind.PublicKeyword))
        return true;
    if (node.Modifiers.Any(SyntaxKind.ProtectedKeyword))
        return !node.Modifiers.Any(SyntaxKind.PrivateKeyword);
    return node.Parent is InterfaceDeclarationSyntax &&
        !node.Modifiers.Any(SyntaxKind.PrivateKeyword) && !node.Modifiers.Any(SyntaxKind.InternalKeyword);
}

static bool IsExplicitInterfaceImplementation(MemberDeclarationSyntax node) => node switch
{
    MethodDeclarationSyntax method => method.ExplicitInterfaceSpecifier != null,
    BasePropertyDeclarationSyntax property => property.ExplicitInterfaceSpecifier != null,
    OperatorDeclarationSyntax operation => operation.ExplicitInterfaceSpecifier != null,
    ConversionOperatorDeclarationSyntax conversion => conversion.ExplicitInterfaceSpecifier != null,
    _ => false,
};

static string QualifiedName(MemberDeclarationSyntax node)
{
    return string.Join(".", node.AncestorsAndSelf().Reverse().Select(ancestor => ancestor switch
    {
        BaseNamespaceDeclarationSyntax ns => ns.Name.ToString(),
        TypeDeclarationSyntax type => type.Identifier.ValueText + type.TypeParameterList,
        BaseTypeDeclarationSyntax type => type.Identifier.ValueText,
        DelegateDeclarationSyntax callable => callable.Identifier.ValueText + callable.TypeParameterList,
        _ => null,
    }).OfType<string>());
}

static string SourceDomain(string path)
{
    string[] parts = path.Split('/');
    // Distinct prototypes and package samples can declare the same global type name.
    return parts[0] == "Samples~" ? string.Join("/", parts.Take(2))
        : path.StartsWith("Assets/Prototypes/", StringComparison.Ordinal) ? string.Join("/", parts.Take(3))
        : "";
}

static string Group(string path)
{
    string[] parts = path.Split('/');
    if (path.StartsWith("Assets/Prototypes/Default/Experiments/", StringComparison.Ordinal))
        return string.Join(" / ", parts.Skip(4).Take(2));
    if (path.StartsWith("Assets/Prototypes/", StringComparison.Ordinal))
        return string.Join(" / ", parts.Skip(1).Take(Math.Min(parts.Length - 2, 3)));
    if (path.StartsWith("Assets/Scripts/", StringComparison.Ordinal))
        return string.Join(" / ", parts.Skip(2).Take(Math.Min(parts.Length - 3, 2)).DefaultIfEmpty("Project scripts"));
    if (path.StartsWith("Assets/Editor/", StringComparison.Ordinal))
        return "Sandbox editor tools";
    return string.Join(" / ", parts.Take(Math.Min(parts.Length - 1, 3))).Replace("Samples~", "Samples");
}

static string Slug(string name) => Regex.Replace(name.ToLowerInvariant(), "[^a-z0-9]+", "-").Trim('-');

static void Add(SortedDictionary<(string Path, int Line, string Signature), ApiDeclaration> target,
    MemberDeclarationSyntax node, string relative)
{
    int line = node.GetLocation().GetLineSpan().StartLinePosition.Line + 1;
    string signature = Signature(node);
    string source = "../../" + string.Join("/", relative.Split('/').Select(Uri.EscapeDataString));
    target.TryAdd((relative, line, signature), new ApiDeclaration(signature, source, line, ReadDocumentation(node)));
}

static string Signature(MemberDeclarationSyntax node)
{
    SyntaxNode header = node switch
    {
        TypeDeclarationSyntax type => type.WithMembers(default).WithOpenBraceToken(default).WithCloseBraceToken(default),
        EnumDeclarationSyntax enumeration => enumeration.WithMembers(default).WithOpenBraceToken(default).WithCloseBraceToken(default),
        MethodDeclarationSyntax method => method.WithBody(null).WithExpressionBody(null),
        ConstructorDeclarationSyntax constructor => constructor.WithBody(null).WithExpressionBody(null).WithInitializer(null),
        DestructorDeclarationSyntax destructor => destructor.WithBody(null).WithExpressionBody(null),
        OperatorDeclarationSyntax operation => operation.WithBody(null).WithExpressionBody(null),
        ConversionOperatorDeclarationSyntax conversion => conversion.WithBody(null).WithExpressionBody(null),
        PropertyDeclarationSyntax property => property.WithInitializer(null).WithExpressionBody(null)
            .WithAccessorList(SignatureAccessors(property.AccessorList, property.ExpressionBody != null)),
        IndexerDeclarationSyntax indexer => indexer.WithExpressionBody(null)
            .WithAccessorList(SignatureAccessors(indexer.AccessorList, indexer.ExpressionBody != null)),
        EventDeclarationSyntax @event => @event.WithAccessorList(SignatureAccessors(@event.AccessorList, false)),
        FieldDeclarationSyntax field when !field.Modifiers.Any(SyntaxKind.ConstKeyword) => field.WithDeclaration(
            field.Declaration.WithVariables(SyntaxFactory.SeparatedList(field.Declaration.Variables.Select(variable => variable.WithInitializer(null))))),
        _ => node,
    };
    // Remove trivia such as documentation, comments and directives inside a multiline declaration.
    string signature = header.ReplaceTrivia(header.DescendantTrivia(), (_, _) => default)
        .NormalizeWhitespace().ToFullString().Trim();
    return signature.TrimEnd(';').TrimEnd();
}

static AccessorListSyntax? SignatureAccessors(AccessorListSyntax? accessors, bool expressionBodied)
{
    if (accessors != null)
        return accessors.WithAccessors(SyntaxFactory.List(accessors.Accessors.Select(accessor =>
            accessor.WithBody(null).WithExpressionBody(null).WithSemicolonToken(SyntaxFactory.Token(SyntaxKind.SemicolonToken)))));
    return expressionBodied ? SyntaxFactory.AccessorList(SyntaxFactory.SingletonList(
        SyntaxFactory.AccessorDeclaration(SyntaxKind.GetAccessorDeclaration)
            .WithSemicolonToken(SyntaxFactory.Token(SyntaxKind.SemicolonToken)))) : null;
}

static string ReadDocumentation(MemberDeclarationSyntax node)
{
    DocumentationCommentTriviaSyntax? comment = node.GetLeadingTrivia().Select(trivia => trivia.GetStructure())
        .OfType<DocumentationCommentTriviaSyntax>().LastOrDefault();
    if (comment == null)
        return "";

    string xml = Regex.Replace(comment.ToFullString(), @"(?m)^\s*/// ?", "");
    try
    {
        XElement docs = XElement.Parse("<doc>" + xml + "</doc>");
        return string.Join("\n", docs.Elements().Select(element =>
        {
            string content = string.Concat(element.Nodes().Select(ReadXmlNode)).Trim();
            string? label = (string?)element.Attribute("name") ?? (string?)element.Attribute("cref");
            return element.Name.LocalName switch
            {
                "summary" or "remarks" => content,
                "paramref" or "typeparamref" => label ?? "",
                "inheritdoc" => "See the inherited contract" + (label == null ? "." : $" on {label}."),
                _ => string.IsNullOrWhiteSpace(content) ? "" : $"{element.Name.LocalName} {label}: {content}",
            };
        }).Where(line => !string.IsNullOrWhiteSpace(line)));
    }
    catch (System.Xml.XmlException)
    {
        return xml.Trim();
    }
}

static string ReadXmlNode(XNode node) => node switch
{
    XText text => text.Value,
    XElement element when element.Name.LocalName is "see" or "seealso" or "paramref" or "typeparamref" =>
        (string?)element.Attribute("cref") ?? (string?)element.Attribute("name") ??
        (string?)element.Attribute("href") ?? element.Value,
    XElement element when element.Name.LocalName is "para" or "code" =>
        "\n" + string.Concat(element.Nodes().Select(ReadXmlNode)) + "\n",
    XElement element => string.Concat(element.Nodes().Select(ReadXmlNode)),
    _ => "",
};

static void AppendDeclaration(StringBuilder markdown, ApiDeclaration declaration)
{
    markdown.AppendLine("```csharp").AppendLine(declaration.Signature).AppendLine("```").AppendLine();
    if (!string.IsNullOrWhiteSpace(declaration.Documentation))
    {
        string prose = Regex.Replace(declaration.Documentation.Trim(), @"\s+", " ");
        markdown.AppendLine(Regex.Replace(prose, @"([\\`*_\[\]<>&|])", @"\$1")).AppendLine();
    }
    markdown.AppendLine($"[Source]({declaration.Source}#L{declaration.Line})").AppendLine();
}

record ApiDeclaration(string Signature, string Source, int Line, string Documentation);

record ApiType(string Name, string QualifiedName, string Anchor, string Group)
{
    public SortedDictionary<(string, int, string), ApiDeclaration> Declarations { get; } = new();
    public SortedDictionary<(string, int, string), ApiDeclaration> Members { get; } = new();
}
