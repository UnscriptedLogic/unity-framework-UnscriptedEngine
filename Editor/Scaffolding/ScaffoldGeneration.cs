using System;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEngine;

namespace UnscriptedEngine.Editor.Scaffolding
{
    /// <summary>Two-phase generation: write source, then build assets after Unity compiles it.</summary>
    [InitializeOnLoad]
    public static class ScaffoldGeneration
    {
        private const string PendingKey = "UnscriptedEngine.Scaffold.Pending";
        public static bool HasPending => !string.IsNullOrEmpty(SessionState.GetString(PendingKey, ""));

        static ScaffoldGeneration() { EditorApplication.update += ResumeWhenReady; }

        private static void ResumeWhenReady()
        {
            if (EditorApplication.isCompiling || EditorApplication.isUpdating) return;
            EditorApplication.update -= ResumeWhenReady;
            TryComplete();
        }

        public static void Start(ScaffoldPlan plan)
        {
            if (HasPending) throw new InvalidOperationException("Finish or cancel the pending generation first.");
            if (EditorApplication.isPlayingOrWillChangePlaymode || EditorApplication.isCompiling)
                throw new InvalidOperationException("Wait for Edit Mode and compilation to finish.");
            plan.Validate();
            IPlayerScaffoldTemplate template = plan.scene ? null : CreateTemplate(plan.templateType);
            plan.EnsureOutputFolders();
            string[] bases = plan.scene
                ? new[] { "UnscriptedEngine.UGameMode", "UnscriptedEngine.UGameInstance", "UnscriptedEngine.UGameState", "Unity.Netcode.NetworkManager" }
                : new[] { "UnscriptedEngine.UController", "UnscriptedEngine.UPawn" };
            var written = new System.Collections.Generic.List<string>();
            try
            {
                for (int i = 0; i < plan.Prefixes.Length; i++)
                {
                    string prefix = plan.Prefixes[i];
                    string body = plan.scene ? "" : i == 0 ? template.ControllerBody : template.PawnBody;
                    string path = plan.PathFor(prefix, "cs");
                    // CreateNew guarantees a collision cannot overwrite another script.
                    using (var stream = new FileStream(path, FileMode.CreateNew, FileAccess.Write))
                    {
                        written.Add(path);
                        using (var writer = new StreamWriter(stream))
                            writer.Write($"// Generated by UnscriptedEngine. Add gameplay in inherited lifecycle hooks.\npublic class {prefix}_{plan.name} : {bases[i]}\n{{\n{body}\n}}\n");
                    }
                }
                SessionState.SetString(PendingKey, JsonUtility.ToJson(plan));
            }
            catch
            {
                foreach (string path in written) File.Delete(path);
                throw;
            }
            AssetDatabase.Refresh();
        }

        public static IPlayerScaffoldTemplate CreateTemplate(string typeName)
        {
            Type type = Type.GetType(typeName ?? "");
            if (type == null || !typeof(IPlayerScaffoldTemplate).IsAssignableFrom(type))
                throw new InvalidOperationException("Player template is unavailable. Restore its Editor assembly before retrying.");
            return (IPlayerScaffoldTemplate)Activator.CreateInstance(type);
        }

        public static Type ResolveScript(ScaffoldPlan plan, string prefix)
        {
            var script = AssetDatabase.LoadAssetAtPath<MonoScript>(plan.PathFor(prefix, "cs"));
            return script == null ? null : script.GetClass();
        }

        public static void TryComplete()
        {
            if (!HasPending || EditorApplication.isCompiling || EditorApplication.isUpdating
                || EditorApplication.isPlayingOrWillChangePlaymode) return;
            var plan = JsonUtility.FromJson<ScaffoldPlan>(SessionState.GetString(PendingKey, ""));
            if (plan.Prefixes.Any(prefix => ResolveScript(plan, prefix) == null)) return;
            try
            {
                if (!ScaffoldAssets.Build(plan)) return;
                SessionState.EraseString(PendingKey);
                Debug.Log($"UnscriptedEngine generated {plan.name} in {plan.folder}.");
            }
            catch (Exception exception)
            {
                Debug.LogException(exception);
                Debug.LogError("Generation remains pending. Fix the error, then use Finish Pending Generation; or cancel it. Existing scripts are retained.");
            }
        }

        public static void Cancel() { SessionState.EraseString(PendingKey); }
    }
}
